  var lang = "ru";

  function t(key) {
    var table = DICT[lang] || DICT.en;
    var text = table[key];
    if (text === undefined) text = DICT.en[key];
    if (text === undefined) text = key;
    for (var i = 1; i < arguments.length; i++) text = text.replace("%s", arguments[i]);
    return text;
  }

  function apply() {
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) { el.title = t(el.dataset.i18nTitle); });
  }

  function setLang(code) {
    lang = DICT[code] ? code : "en";
    apply();
    return lang;
  }

  window.I18N = { t: t, setLang: setLang, apply: apply, get: function () { return lang; } };
